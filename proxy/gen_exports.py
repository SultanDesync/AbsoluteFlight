"""Generate the winmm proxy's export stubs from System32\\winmm.dll (D22, T100).

Writes src/exports.rs (one jump stub per export, through a table filled from the real DLL at load) and
winmm.def (same names and ordinals as the system DLL). Rerun after a Windows update adds exports:
    .venv\\Scripts\\python proxy\\gen_exports.py
"""
import os
from pathlib import Path

import pefile

HERE = Path(__file__).resolve().parent
SYSTEM = Path(os.environ['SystemRoot']) / 'System32' / 'winmm.dll'


def main():
    pe = pefile.PE(str(SYSTEM), fast_load=True)
    pe.parse_data_directories(directories=[pefile.DIRECTORY_ENTRY['IMAGE_DIRECTORY_ENTRY_EXPORT']])
    symbols = sorted(pe.DIRECTORY_ENTRY_EXPORT.symbols, key=lambda s: s.ordinal)
    assert not any(s.forwarder for s in symbols), 'system winmm forwards exports; stubs would need a rework'
    entries = [(s.name.decode() if s.name else None, s.ordinal) for s in symbols]
    stub = lambda name, ordinal: f'af_winmm_{name}' if name else f'af_winmm_ord{ordinal}'

    asm = [f'.globl {stub(n, o)}\n{stub(n, o)}:\n    jmp qword ptr [rip + AF_WINMM_TABLE + {8 * i}]' for i, (n, o) in enumerate(entries)]
    rust_name = lambda name: 'Some(b"' + name + '\\0")' if name else 'None'
    rows = [f'    ({rust_name(n)}, {o}),' for n, o in entries]
    (HERE / 'src' / 'exports.rs').write_text(
        f'// Generated by proxy/gen_exports.py from System32\\winmm.dll ({len(entries)} exports). Do not edit.\n'
        f'pub const COUNT: usize = {len(entries)};\n\n'
        '/// (name, ordinal) of every winmm export, in AF_WINMM_TABLE order.\n'
        f'pub static EXPORTS: [(Option<&[u8]>, u16); COUNT] = [\n' + '\n'.join(rows) + '\n];\n\n'
        '#[no_mangle]\npub static mut AF_WINMM_TABLE: [usize; COUNT] = [0; COUNT];\n\n'
        'core::arch::global_asm!(\n'
        + '\n'.join(f'    "{line}",' for block in asm for line in block.split('\n'))
        + '\n);\n', encoding='utf-8', newline='\n')
    lines = ['LIBRARY winmm', 'EXPORTS'] + [
        f'    {n}={stub(n, o)} @{o}' if n else f'    {stub(n, o)} @{o} NONAME' for n, o in entries]
    (HERE / 'winmm.def').write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
    print(f'{len(entries)} exports from {SYSTEM}')


if __name__ == '__main__':
    main()
